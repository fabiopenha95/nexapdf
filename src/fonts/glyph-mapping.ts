/**
 * Mapeamento Unicode → WinAnsiEncoding (PDF 1.7, Anexo D.2).
 *
 * As fontes padrão (Standard 14) da Fase 1 usam codificação de um byte.
 * 0x20–0x7E e 0xA0–0xFF coincidem com Latin-1; 0x80–0x9F contêm a
 * pontuação tipográfica do Windows-1252.
 */

const C1: Readonly<Record<number, number>> = {
  0x20ac: 0x80, 0x201a: 0x82, 0x0192: 0x83, 0x201e: 0x84, 0x2026: 0x85, 0x2020: 0x86, 0x2021: 0x87,
  0x02c6: 0x88, 0x2030: 0x89, 0x0160: 0x8a, 0x2039: 0x8b, 0x0152: 0x8c, 0x017d: 0x8e, 0x2018: 0x91,
  0x2019: 0x92, 0x201c: 0x93, 0x201d: 0x94, 0x2022: 0x95, 0x2013: 0x96, 0x2014: 0x97, 0x02dc: 0x98,
  0x2122: 0x99, 0x0161: 0x9a, 0x203a: 0x9b, 0x0153: 0x9c, 0x017e: 0x9e, 0x0178: 0x9f,
};

/** Substituições visuais para caracteres comuns fora do WinAnsi. */
const FALLBACKS: Readonly<Record<number, number>> = {
  0x2212: 0x2d, // minus → hífen
  0x2010: 0x2d, 0x2011: 0x2d, // hífens
  0x2002: 0x20, 0x2003: 0x20, 0x2009: 0x20, 0x200a: 0x20, 0x202f: 0x20, 0x2007: 0x20, 0x2008: 0x20,
  0x25e6: 0x95, // ◦ → •
  0x2032: 0x27, 0x2033: 0x22, // ′ ″
  0x00ad: 0x2d, // hífen suave (quando exibido)
};

export const REPLACEMENT_BYTE = 0x3f; // "?"

/** Retorna o byte WinAnsi para um code point, ou -1 se não houver. */
export function winAnsiByte(cp: number): number {
  if ((cp >= 0x20 && cp <= 0x7e) || (cp >= 0xa0 && cp <= 0xff)) return cp;
  return C1[cp] ?? FALLBACKS[cp] ?? -1;
}

/** Codifica uma string em bytes WinAnsi; caracteres sem mapeamento viram "?". */
export function encodeWinAnsi(text: string): Uint8Array {
  const bytes: number[] = [];
  for (const ch of text) {
    const b = winAnsiByte(ch.codePointAt(0)!);
    bytes.push(b === -1 ? REPLACEMENT_BYTE : b);
  }
  return Uint8Array.from(bytes);
}

export function isEncodable(cp: number): boolean {
  return winAnsiByte(cp) !== -1;
}
